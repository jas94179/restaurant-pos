"""Generate app/src/design/tokens.ts from design-system/tokens.json.
Run from design-system/:  python3 make_rn_tokens.py"""
import json, re, pathlib
d = json.load(open('tokens.json'))
prim = {t['name']: t['value'] for t in d['color']['tokens'] if isinstance(t['value'], str)}
roles = [t for t in d['color']['tokens'] if isinstance(t['value'], dict)]
def res(v):
    m = re.fullmatch(r'\{(.+)\}', v)
    return prim[m.group(1)] if m else v
def camel(n): return re.sub(r'-(\w)', lambda m: m.group(1).upper(), n)
def px(v): return float(v.replace('px', ''))
def num(v): f = float(v); return int(f) if f.is_integer() else f
out = ['// GENERATED by design-system/make_rn_tokens.py from design-system/tokens.json.',
       '// Do not edit by hand: change tokens.json and run the script again.',
       '// galla Design System v%s. The app ships the light theme; dark is defined for later.' % d['version'], '']
out.append('export const palette = {')
for k, v in prim.items(): out.append(f"  {camel(k).replace('-', '')}: '{v}',")
out.append('} as const;\n')
for th in ('light', 'dark'):
    out.append(f'const {th}Colors = {{')
    for t in roles:
        out.append(f"  {camel(t['name'])}: '{res(t['value'][th])}', // {t.get('usage','')}")
    out.append('};\n')
out.append('export type ColorRoles = typeof lightColors;')
out.append('export const themes: Record<\'light\' | \'dark\', ColorRoles> = { light: lightColors, dark: darkColors };\n')
def fam(n):
    out.append(f'export const {n} = {{')
    for t in d[n]['tokens']:
        key = camel(re.sub(r'^(space|radius|size|stroke|duration|opacity|ease)-', '', t['name']))
        v = t['value']
        if isinstance(v, str) and v.endswith('px'): val = num(px(v))
        elif isinstance(v, str) and v.endswith('ms'): val = num(v[:-2])
        elif n == 'easing':
            val = '[' + v[v.index('(')+1:-1] + ']'
            val = val + ' as const'
        else: val = num(v) if re.fullmatch(r'[\d.]+', str(v)) else repr(v)
        out.append(f"  {key if re.fullmatch(r'[A-Za-z_]\w*|\d+', key) else repr(key)}: {val},")
    out.append('};\n')
for n in ('spacing', 'radius', 'size', 'stroke', 'duration', 'easing', 'opacity'): fam(n)
# shadows -> RN
def rn_shadow(css):
    m = re.fullmatch(r'0 (\d+)px (\d+)px rgba\((\d+),(\d+),(\d+),([\d.]+)\)', css)
    y, blur, r, g, b, a = m.groups()
    return f"{{ shadowColor: 'rgb({r},{g},{b})', shadowOffset: {{ width: 0, height: {y} }}, shadowOpacity: {a}, shadowRadius: {int(blur)//2}, elevation: {max(1,int(blur)//3)} }}"
for th in ('light', 'dark'):
    out.append(f'const {th}Shadows = {{')
    for t in d['shadow']['tokens']:
        out.append(f"  {camel(t['name']).replace('shadow', 's')}: {rn_shadow(t['value'][th])},")
    out.append('};')
out.append('export const shadows = { light: lightShadows, dark: darkShadows };\n')
# type
W = {400: 'BricolageGrotesque_400Regular', 600: 'BricolageGrotesque_600SemiBold', 800: 'BricolageGrotesque_800ExtraBold'}
out.append('// App text styles. Marketing (Poppins) styles live in the web/brochure work, not the app.')
out.append('export const typography = {')
for g in d['type']['groups']:
    if g['name'] != 'App': continue
    for s in g['styles']:
        fs = px(s['fontSize']); lh = px(s['lineHeight'])
        ls = s.get('letterSpacing', '0')
        lsv = round(float(ls.replace('em', '')) * fs, 2) if 'em' in str(ls) else (px(ls) if 'px' in str(ls) else 0)
        extra = ", fontVariant: ['tabular-nums'] as ['tabular-nums']" if 'amount' in s['name'] else ''
        out.append(f"  {camel(s['name'])}: {{ fontFamily: '{W.get(s['fontWeight'], W[600])}', fontSize: {num(fs)}, lineHeight: {num(lh)}, letterSpacing: {lsv}{extra} }}, // {s.get('usage','')}")
out.append('};\n')
p = pathlib.Path('../app/src/design/tokens.ts'); p.parent.mkdir(exist_ok=True)
p.write_text('\n'.join(out) + '\n'); print('wrote', p, len(out), 'lines')
